#!/usr/bin/env node
/**
 * Cloudflare Workers (workerd) runtime smoke test.
 *
 * The s200/cloudflare adapter is one line over handle(): createHandler(app)
 * returns the module-worker `fetch` default export. This smoke proves that
 * shape against REAL workerd, driven by miniflare:
 *
 *   - a tmp worker entry exports createHandler(app) and imports the built
 *     dist/cloudflare.mjs (plus dist/index.mjs for the app-building
 *     surface) as sibling modules, so workerd resolves plain relative
 *     specifiers;
 *   - the dist module graph is copied next to the entry, because miniflare
 *     loads exactly the modules it is given: every transitive relative
 *     import (vite's flat hash-named chunk siblings) is listed in the
 *     explicit ModuleDefinition array;
 *   - dispatchFetch (any host — it is ignored) drives the full chain: the
 *     param route's JSON body, the in-chain 404 fallback, and a
 *     middleware stamp on the unwind;
 *   - when dist/websocket-cloudflare.mjs is built, the same worker wires
 *     the WebSocket bridge (`??` composition with createHandler) and the
 *     smoke drives a real upgrade round trip: handshake 101 + client
 *     socket, an echoed message, subprotocol negotiation (server
 *     preference order), a middleware rejection answered as plain HTTP,
 *     and the plain-GET fall-through.
 *
 * Expects miniflare's classic ModuleDefinition API (v3/v4 — CI pins the
 * stable 4 line; the 5.x line is alpha-only and reworked the constructor
 * around a `workers[]` array).
 *
 * Auto-skips with one printed line when miniflare isn't installed or the
 * dist isn't built (never throws) — CI installs miniflare, so the gate is
 * real there.
 *
 * Run: node scripts/smoke-cloudflare.mjs — exits 0 when every check
 * passes (or on skip), 1 otherwise.
 */
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

let Miniflare;
try {
  // miniflare is an optional smoke tool — absent installs skip below.
  // eslint-disable-next-line import-x/no-unresolved
  ({ Miniflare } = await import('miniflare'));
} catch {
  console.log('cloudflare smoke: miniflare not installed, skipping');
  process.exit(0);
}

const distDir = fileURLToPath(new URL('../dist', import.meta.url));
const distCloudflare = join(distDir, 'cloudflare.mjs');
const distBarrel = join(distDir, 'index.mjs');
const distWsCloudflare = join(distDir, 'websocket-cloudflare.mjs');
if (!existsSync(distCloudflare) || !existsSync(distBarrel)) {
  console.log('cloudflare smoke: dist/cloudflare.mjs not built (run pnpm build first), skipping');
  process.exit(0);
}
// The WebSocket bridge section needs its built entry; absence only skips
// that section (the HTTP checks below still run).
const hasWsBridge = existsSync(distWsCloudflare);

// workerd only sees the modules miniflare lists, so copy the transitive
// closure of relative imports (vite's flat hash-named chunk siblings) into
// the tmp dir next to the generated entry — every specifier stays a plain
// "./sibling.mjs", both inside the graph and in workerd's module name
// space (names are paths relative to modulesRoot, which defaults to cwd).
const dir = mkdtempSync(join(tmpdir(), 's200-cloudflare-smoke-'));
const entry = join(dir, 'worker.mjs');
const copied = [];
{
  const queue = [distCloudflare, distBarrel];
  if (hasWsBridge) {
    queue.push(distWsCloudflare);
  }
  const seen = new Set();
  while (queue.length > 0) {
    const file = queue.pop();
    if (seen.has(file)) {
      continue;
    }
    seen.add(file);
    cpSync(file, join(dir, basename(file)));
    copied.push(basename(file));
    const code = readFileSync(file, 'utf8');
    for (const match of code.matchAll(/from\s*["'](\.{1,2}\/[^"']+)["']/g)) {
      queue.push(join(distDir, match[1]));
    }
  }
}

writeFileSync(
  entry,
  `// Generated by scripts/smoke-cloudflare.mjs — safe to delete.
import { createApp, get, json, use } from './index.mjs';
import { createHandler } from './cloudflare.mjs';
${hasWsBridge ? `import { upgradeWebSocket } from './websocket.mjs';
import { createCloudflareWebSocketBridge } from './websocket-cloudflare.mjs';` : ''}

const app = createApp();

// Probe: after next() resolves, every response — the
// handler's, the 404 fallback — must already exist, so the unwind can
// observe and re-stamp it.
use(app, async (ctx, next) => {
  await next();
  if (ctx.res !== undefined) {
    const headers = new Headers(ctx.res.headers);
    headers.set('x-s200', 'cloudflare');
    ctx.res = new Response(ctx.res.body, {
      status: ctx.res.status,
      statusText: ctx.res.statusText,
      headers,
    });
  }
});

get(app, '/hello', (ctx) => json(ctx, { hello: 'workerd' }));
get(app, '/users/:id', (ctx) => json(ctx, { id: ctx.params.id }));

${
  hasWsBridge
    ? `// WebSocket: an echo route with a room param, a subprotocol route
// (echoes the negotiated protocol), and a gated one whose middleware
// rejects with 401 — plus the bridge ?? createHandler composition.
upgradeWebSocket(app, '/echo/:room', (socket, ctx) => {
  socket.onMessage((data) => socket.send('[' + ctx.params.room + '] ' + String(data)));
});
upgradeWebSocket(app, '/proto', (socket) => {
  socket.onMessage(() => socket.send(socket.protocol ?? 'none'));
}, { protocols: ['chat.b', 'chat.a'] });
upgradeWebSocket(app, '/gated', async (ctx) => {
  ctx.res = new Response('no token', { status: 401 });
}, () => {});

const ws = createCloudflareWebSocketBridge(app);
const worker = createHandler(app);
export default {
  fetch: (request, env, ctx) =>
    ws.upgrade(request).then((res) => res ?? worker.fetch(request, env, ctx)),
};
`
    : 'export default createHandler(app);\n'
}`
);

let failures = 0;
function check(name, ok, detail) {
  if (ok) {
    console.log(`ok   ${name}`);
  } else {
    failures += 1;
    console.error(`FAIL ${name} — ${detail}`);
  }
}

const mf = new Miniflare({
  // workerd uses the first module as the entrypoint; transitive
  // dependencies must follow (miniflare no longer auto-locates them).
  // modulesRoot keeps every module name relative to the tmp dir —
  // without it names are relative to cwd and workerd rejects the
  // `..` path escape from the project into the OS tmp dir.
  modulesRoot: dir,
  modules: [
    { type: 'ESModule', path: entry },
    ...copied.map((name) => ({ type: 'ESModule', path: join(dir, name) })),
  ],
  // A safely-past date: the bundle feature-guards its modern-API use
  // (AbortSignal.any et al) anyway; this only keeps workerd from
  // defaulting to "a date far in the past".
  compatibilityDate: '2025-01-01',
});

try {
  // dispatchFetch ignores the host — any URL routes to the worker.
  const hello = await mf.dispatchFetch('http://smoke/hello');
  const helloBody = await hello.json();
  check('GET /hello status 200', hello.status === 200, `got ${hello.status}`);
  check(
    'GET /hello body {"hello":"workerd"}',
    JSON.stringify(helloBody) === '{"hello":"workerd"}',
    JSON.stringify(helloBody),
  );
  check(
    'middleware stamps its header on the unwind',
    hello.headers.get('x-s200') === 'cloudflare',
    `got ${hello.headers.get('x-s200')}`,
  );

  const user = await mf.dispatchFetch('http://smoke/users/42');
  const userBody = await user.json();
  check(
    'GET /users/:id answers 200 with the decoded param',
    user.status === 200 && JSON.stringify(userBody) === '{"id":"42"}',
    `status ${user.status}, body ${JSON.stringify(userBody)}`,
  );

  const missing = await mf.dispatchFetch('http://smoke/nope');
  const missingBody = await missing.json();
  check('GET /nope falls back to 404', missing.status === 404, `got ${missing.status}`);
  check(
    '404 fallback body {"error":"Not Found"}',
    JSON.stringify(missingBody) === '{"error":"Not Found"}',
    JSON.stringify(missingBody),
  );
  check(
    'onion unwind sees the in-chain 404',
    missing.headers.get('x-s200') === 'cloudflare',
    `got ${missing.headers.get('x-s200')}`,
  );

  if (!hasWsBridge) {
    console.log('cloudflare smoke: dist/websocket-cloudflare.mjs not built — ws section skipped');
  } else {
    // Upgrade round trip: dispatchFetch carries the 101 response with the
    // pair's client end on `webSocket`; accept() it host-side, then one
    // echoed message proves the handler received socket + ctx.
    const wsRes = await mf.dispatchFetch('http://smoke/echo/general', {
      headers: { Upgrade: 'websocket' },
    });
    const client = wsRes.webSocket;
    check(
      'ws handshake answers 101 with the client socket',
      wsRes.status === 101 && client !== undefined && typeof client.accept === 'function',
      `status ${wsRes.status}, webSocket ${String(client)}`,
    );
    client.accept();
    const echoed = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('echo timeout')), 5000);
      client.addEventListener('message', (event) => {
        clearTimeout(timer);
        resolve(event.data);
      });
      client.addEventListener('error', () => {
        clearTimeout(timer);
        reject(new Error('socket error'));
      });
      client.send('hi');
    });
    check(
      'ws message round trips through the handler',
      echoed === '[general] hi',
      `got ${String(echoed)}`,
    );
    client.close(1000, 'done');

    // Subprotocol: both ends offered, server preference order wins and
    // reaches the handler's socket.protocol.
    const protoRes = await mf.dispatchFetch('http://smoke/proto', {
      headers: { Upgrade: 'websocket', 'Sec-WebSocket-Protocol': 'chat.a, chat.b' },
    });
    const protoClient = protoRes.webSocket;
    check(
      'ws subprotocol handshake upgrades',
      protoRes.status === 101 && protoClient !== undefined,
      `status ${protoRes.status}`,
    );
    protoClient.accept();
    const echoedProto = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('echo timeout')), 5000);
      protoClient.addEventListener('message', (event) => {
        clearTimeout(timer);
        resolve(event.data);
      });
      protoClient.addEventListener('error', () => {
        clearTimeout(timer);
        reject(new Error('socket error'));
      });
      protoClient.send('p');
    });
    check(
      'ws negotiated protocol is the server preference (chat.b)',
      echoedProto === 'chat.b',
      `got ${String(echoedProto)}`,
    );
    protoClient.close(1000, 'done');

    // A rejecting middleware answers plain HTTP, never a pair.
    const gated = await mf.dispatchFetch('http://smoke/gated', {
      headers: { Upgrade: 'websocket' },
    });
    check(
      'ws middleware rejection answers 401 as plain HTTP',
      gated.status === 401 && (await gated.text()) === 'no token',
      `status ${gated.status}`,
    );

    // Plain GET (no Upgrade header) falls through to the HTTP chain.
    const plain = await mf.dispatchFetch('http://smoke/echo/general');
    check(
      'plain GET to a ws path falls through to HTTP 404',
      plain.status === 404,
      `got ${plain.status}`,
    );
  }
} catch (error) {
  failures += 1;
  console.error(`FAIL workerd dispatch — ${String(error)}`);
} finally {
  await mf.dispose();
  rmSync(dir, { recursive: true, force: true });
}

if (failures > 0) {
  console.error(`\ncloudflare smoke FAILED — ${failures} check(s) failed`);
  process.exit(1);
}
console.log('\ncloudflare smoke OK — all checks passed on workerd (miniflare)');
